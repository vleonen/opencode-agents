// Generate src/generated/agents.ts from agents/*.md and AGENTS.agents.md.
//
//   node scripts/gen-agents.mjs           rewrite the generated module
//   node scripts/gen-agents.mjs --check    fail if the committed module is stale
//
// The agent Markdown files stay the human-readable source of truth; the
// generated module is what the plugin and CLI read at runtime (no filesystem
// path resolution, so it works whether opencode loads src/index.ts directly or
// esbuild bundles the CLI).
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const here = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(here, "..")
const agentsDir = path.join(root, "agents")
const policyFile = path.join(root, "AGENTS.agents.md")
const outFile = path.join(root, "src", "generated", "agents.ts")

const ROLES = ["designer", "qa", "reviewer"]
const VARIANTS = [
  ["", "primary"],
  ["-fallback", "fallback"],
]

const entries = []
for (const role of ROLES) {
  for (const [suffix, kind] of VARIANTS) {
    const fileName = `${role}${suffix}.md`
    const content = fs.readFileSync(path.join(agentsDir, fileName), "utf8")
    entries.push({ fileName, role, kind, content })
  }
}

const policy = fs.readFileSync(policyFile, "utf8")

const header = [
  "// AUTO-GENERATED by scripts/gen-agents.mjs — do not edit by hand.",
  "// Source of truth: agents/*.md and AGENTS.agents.md",
  "",
  'export type AgentTemplateKind = "primary" | "fallback"',
  "",
  "export interface AgentTemplate {",
  "  fileName: string",
  "  role: string",
  "  kind: AgentTemplateKind",
  "  content: string",
  "}",
  "",
].join("\n")

const body = `${header}export const AGENT_TEMPLATES: AgentTemplate[] = ${JSON.stringify(entries, null, 2)}\n\nexport const POLICY_TEMPLATE = ${JSON.stringify(policy)}\n`

if (process.argv.includes("--check")) {
  const current = fs.existsSync(outFile) ? fs.readFileSync(outFile, "utf8") : ""
  if (current !== body) {
    console.error("generated src/generated/agents.ts is out of date — run `npm run gen`")
    process.exit(1)
  }
  console.log("generated src/generated/agents.ts is up to date")
} else {
  fs.mkdirSync(path.dirname(outFile), { recursive: true })
  fs.writeFileSync(outFile, body)
  console.log(`wrote ${path.relative(root, outFile)} (${entries.length} templates)`)
}
